// Builds docs/bioinformatics/shared/data/essay-06.json: independent references for
// essay 06's checks.
//   scipy: average-linkage merge heights and clusters for Figure 1's simulated matrix,
//          from scipy.cluster.hierarchy.linkage(Z, method="average", metric="correlation")
//   cpgs:  the four CDKN1A promoter CpGs the cohort figures use, read from locus.json
// Usage: node scripts/bio-06-reference.mjs   (needs python3 with numpy and scipy)
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const shared = path.join(root, "docs/bioinformatics/shared");
const E = require(path.join(shared, "essay-06.js"));
const BL = require(path.join(shared, "locus.js"));

const G = E.geneMatrix();
const py = `
import json, sys
import numpy as np
from scipy.cluster.hierarchy import linkage
Z = np.array(json.load(sys.stdin))
L = linkage(Z, method="average", metric="correlation")
n = Z.shape[0]
members = {i: [i] for i in range(n)}
clusters = []
for i, row in enumerate(L):
    m = members[int(row[0])] + members[int(row[1])]
    members[n + i] = m
    clusters.append(sorted(m))
print(json.dumps({"heights": [float(h) for h in L[:, 2]], "clusters": clusters}))
`;
const ref = JSON.parse(execFileSync("python3", ["-c", py], { input: JSON.stringify(G.Z) }).toString());
const scipyVersion = execFileSync("python3", ["-c", "import scipy; print(scipy.__version__)"]).toString().trim();

const L = BL.load(require(path.join(shared, "data/locus.json")));
const R = L.region("cdkn1a"), tx = R.canonical("CDKN1A");
const cpgs = E.CPG_OFFSETS.map(o => {
  const pos1 = R.posFromTSS(o, tx);
  return { offset: o, pos1, dinuc: R.seq1(pos1, pos1 + 1).toUpperCase() };
});

const out = {
  note: "References for essay 06 checks. Generated by scripts/bio-06-reference.mjs; do not edit.",
  scipy: { version: scipyVersion, method: "linkage(method='average', metric='correlation') on BioEssay06.geneMatrix().Z",
    sumX: Math.round(G.X.flat().reduce((a, b) => a + b, 0) * 1e6) / 1e6, heights: ref.heights, clusters: ref.clusters },
  cpgs: cpgs,
  cpgSource: "locus.json (UCSC hg38 chr6), offsets from the Ensembl canonical CDKN1A TSS chr6:36,678,714, promoter convention"
};
writeFileSync(path.join(shared, "data/essay-06.json"), JSON.stringify(out, null, 1) + "\n");
console.log("wrote essay-06.json:", ref.heights.length, "merges; CpGs", cpgs.map(c => c.offset + ":" + c.dinuc).join(" "));
