// Build docs/sheaves/data/intel-lab.js for sheaves essay 03 from the Intel
// Berkeley Research Lab sensor data (Bodik, Hong, Guestrin, Madden, Paskin,
// Thibaux, 2004), https://db.csail.mit.edu/labdata/labdata.html
//
//   curl -LO https://db.csail.mit.edu/labdata/data.txt.gz
//   curl -LO https://db.csail.mit.edu/labdata/mote_locs.txt
//   node scripts/sheaves-intel-lab.mjs data.txt.gz mote_locs.txt
//
// Output: temperature per mote as the median of its readings in each
// 30-minute bin from 2004-03-07 00:00 to 2004-03-10 00:00 (144 bins), null
// where a mote sent nothing. Neighbours are the Delaunay edges of the mote
// positions no longer than 8 m. Needs docs/vendor (./scripts/vendor.sh) for d3.
import fs from 'node:fs';
import zlib from 'node:zlib';
import readline from 'node:readline';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const d3 = require('../docs/vendor/js/d3.v7.min.js');
const [gzPath, locPath] = process.argv.slice(2);
if (!gzPath || !locPath) { console.error('usage: node scripts/sheaves-intel-lab.mjs data.txt.gz mote_locs.txt'); process.exit(1); }

const START = Date.UTC(2004, 2, 7), BIN = 30 * 60 * 1000, NBIN = 144, LMAX = 8;
const bins = new Map();
const rl = readline.createInterface({ input: fs.createReadStream(gzPath).pipe(zlib.createGunzip()) });
for await (const line of rl) {
  const p = line.trim().split(/\s+/);
  if (p.length < 8) continue;
  const t = Date.parse(p[0] + 'T' + p[1].slice(0, 8) + 'Z'), m = +p[3], T = +p[4];
  if (!Number.isFinite(t) || !Number.isFinite(T)) continue;
  const b = Math.floor((t - START) / BIN);
  if (b < 0 || b >= NBIN) continue;
  const key = m + ':' + b;
  if (!bins.has(key)) bins.set(key, []);
  bins.get(key).push(T);
}

const locs = fs.readFileSync(locPath, 'utf8').trim().split('\n').map(l => l.trim().split(/\s+/).map(Number));
const motes = locs.filter(([id]) => [...Array(NBIN).keys()].some(b => bins.has(id + ':' + b)))
  .map(([id, x, y]) => ({ id, x, y }));
const temp = motes.map(m => Array.from({ length: NBIN }, (_, b) => {
  const v = bins.get(m.id + ':' + b);
  return v ? Math.round(d3.median(v) * 100) / 100 : null;
}));

const del = d3.Delaunay.from(motes, m => m.x, m => m.y), seen = new Set(), edges = [];
for (let t = 0; t < del.triangles.length; t += 3) for (let k = 0; k < 3; k++) {
  const i = del.triangles[t + k], j = del.triangles[t + (k + 1) % 3], a = Math.min(i, j), b = Math.max(i, j);
  if (seen.has(a + ',' + b)) continue;
  seen.add(a + ',' + b);
  if (Math.hypot(motes[a].x - motes[b].x, motes[a].y - motes[b].y) <= LMAX) edges.push([a, b]);
}
edges.sort((e, f) => e[0] - f[0] || e[1] - f[1]);

const out = {
  source: 'Intel Berkeley Research Lab, 54 Mica2Dot motes, Feb 28 - Apr 5 2004. P. Bodik, W. Hong, C. Guestrin, S. Madden, M. Paskin, R. Thibaux. https://db.csail.mit.edu/labdata/labdata.html',
  start: '2004-03-07T00:00', stepMinutes: 30,
  note: 'temperature in C, median per mote per 30-minute bin, null where the mote sent nothing; x, y in metres from the upper right corner of the lab; edges are Delaunay edges up to 8 m',
  motes, edges, temp
};
const header = '// Generated by scripts/sheaves-intel-lab.mjs. Intel Berkeley Research Lab data,\n// used with the acknowledgement its authors ask for (see `source`).\n';
fs.mkdirSync('docs/sheaves/data', { recursive: true });
fs.writeFileSync('docs/sheaves/data/intel-lab.js', header + 'window.INTEL_LAB = ' + JSON.stringify(out) + ';\n');
console.log(motes.length, 'motes,', edges.length, 'edges,', temp.flat().filter(v => v == null).length, 'missing of', motes.length * NBIN);
